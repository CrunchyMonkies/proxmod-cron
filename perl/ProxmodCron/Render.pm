package ProxmodCron::Render;

use strict;
use warnings;

use ProxmodCron::Config;
use ProxmodCron::Registry;
use ProxmodCron::Spec;

# Definitions -> the text of one /etc/cron.d file.
#
# Pure: render() takes a store and a node name and returns a string. It touches
# no filesystem, which is why most of the test suite points here.
#
# Two cron rules are load-bearing and are handled in exactly one place, below:
#
#   * cron hands the command to $SHELL, so every argv element is shell-quoted
#     here and nowhere else.
#   * '%' in a crontab command means "newline, and everything after is stdin".
#     An unescaped one silently truncates the job. It is escaped after quoting,
#     because cron reads the line before the shell does.

our $VERSION = '0.1.0';

our $EXEC = ProxmodCron::Config::prefix() . '/usr/lib/proxmod-cron/proxmod-cron-exec';

our $BANNER = 'Generated by proxmod-cron. Do not edit - changes are overwritten.';

our $PATH = '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin';

my %FILENAME = (
    cluster => 'proxmod-cron-cluster',
    node => 'proxmod-cron-node',
);

=head2 filename($scope)

The generated file's base name. No '.' in it, ever: cron ignores a file in
/etc/cron.d whose name contains a dot, and the failure is completely silent.

=cut

sub filename {
    my ($scope) = @_;
    return $FILENAME{$scope} || die "unknown scope '$scope'\n";
}

sub path {
    my ($scope) = @_;
    return ProxmodCron::Config::cron_d() . '/' . filename($scope);
}

=head2 render($scope, $store, $nodename)

The whole file. Returns undef when nothing renders for this node, which is the
signal to remove the file rather than leave an empty one behind.

=cut

sub render {
    my ($scope, $store, $nodename) = @_;

    my @lines;
    my @body;
    my $count = 0;

    for my $id (sort keys %{ $store->{jobs} || {} }) {
        my $job = ProxmodCron::Config::effective($scope, $store, $id);
        next if !$job;

        next if $scope eq 'cluster' && !ProxmodCron::Config::targets_node($job, $nodename);

        push @body, render_job($job);
        $count++;
    }

    return undef if !$count;

    push @lines, "# $BANNER";
    push @lines, '# Source: ' . ProxmodCron::Config::file_for($scope)
        . '   Scope: ' . $scope
        . (defined($nodename) ? "   Node: $nodename" : '')
        . "   Jobs: $count";
    push @lines, 'SHELL=/bin/sh';
    push @lines, "PATH=$PATH";
    push @lines, 'MAILTO=' . _mailto($store);
    push @lines, '';

    return join("\n", @lines, @body) . "\n";
}

# Cron's default is to mail a job's output to its user, which on a hypervisor
# means mail nobody reads. Emptying it is only defensible because
# proxmod-cron-exec captures that output into journald instead — the two
# decisions are one decision. An administrator who does want the mail sets
# `mailto` on the store.
sub _mailto {
    my ($store) = @_;

    my $mailto = defined($store->{mailto}) ? $store->{mailto} : '';
    return '""' if $mailto eq '';

    # Anything that is not a plain address is dropped rather than rendered: this
    # line is read by cron itself, and a newline in it would inject a job.
    return '""' if $mailto !~ /\A[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\z/;

    return $mailto;
}

=head2 render_job($job)

The comment header and the crontab line for one effective job, as a list of
lines. A job whose plugin will not load renders as comments naming the missing
type — never silently dropped, and never executed with a guessed command.

=cut

sub render_job {
    my ($job) = @_;

    my @out;

    my $label = "# job: $job->{id} ($job->{type})";
    $label .= ' [' . $job->{owner} . ']' if $job->{origin} eq 'extension' && $job->{owner};
    $label .= ' - ' . _comment_text($job->{comment}) if defined $job->{comment} && $job->{comment} ne '';
    $label .= ' - DISABLED' if !$job->{enabled};

    push @out, $label;

    my $argv = eval { ProxmodCron::Registry::build_command($job->{type}, $job) };
    if (!$argv) {
        my $why = $@ || "job type '$job->{type}' produced no command\n";
        chomp $why;
        push @out, '# UNAVAILABLE: ' . _comment_text($why);
        push @out, '';
        return @out;
    }

    my $command = join(' ', map { quote($_) } @{ wrap($job, $argv) });

    my $line = join("\t", $job->{schedule}, $job->{user}, escape_percent($command));

    # A disabled job stays in the file as a comment rather than disappearing, so
    # `cat /etc/cron.d/proxmod-cron-node` still shows everything that is defined.
    push @out, ($job->{enabled} ? $line : "#$line");
    push @out, '';

    return @out;
}

=head2 wrap($job, $argv)

The argv cron actually runs: the job's own command, inside the run wrapper when
the job is tracked.

Shared with C<proxmod-cronctl run> so that running a job by hand runs the same
thing the schedule does — including the tracking, which is what puts a manual
run in the same history as a scheduled one.

=cut

sub wrap {
    my ($job, $argv) = @_;

    return [@$argv] if !$job->{track};

    my @wrapper = ($EXEC, $job->{scope}, $job->{id});
    push @wrapper, '--no-output' if !$job->{keep_output};

    return [@wrapper, '--', @$argv];
}

# A comment is still a line in a file cron parses. A newline would end the
# comment and start something else.
sub _comment_text {
    my ($text) = @_;
    my $out = defined($text) ? $text : '';
    $out =~ s/[\r\n]+/ /g;
    $out =~ s/\s+\z//;
    return $out;
}

=head2 quote($arg)

Shell-quote one argv element. Left bare when it is unambiguously safe, because
the readability of the generated file is the reason native cron was chosen as
the engine.

=cut

sub quote {
    my ($arg) = @_;

    $arg = '' if !defined $arg;

    return q{''} if $arg eq '';
    return $arg if $arg =~ m{\A[A-Za-z0-9_./:=@,+-]+\z};

    # Single quotes protect everything except a single quote, which is closed,
    # escaped and reopened.
    my $out = $arg;
    $out =~ s/'/'\\''/g;

    return "'$out'";
}

=head2 escape_percent($text)

Escape '%' for cron. Applied to the finished command, after quoting: cron
processes the line before the shell sees it, so quoting does not protect a '%'.

=cut

sub escape_percent {
    my ($text) = @_;
    my $out = defined($text) ? $text : '';
    $out =~ s/%/\\%/g;
    return $out;
}

=head2 summary($scope, $store, $nodename)

What GET jobs returns per row, minus the permission flags the API adds: the
rendered command, whether it renders on this node at all, and the next run.

Sharing this with the renderer is deliberate — the command the UI shows and the
command cron runs are built by the same code path, so they cannot drift.

=cut

sub summary {
    my ($scope, $store, $nodename) = @_;

    my @rows;

    for my $id (sort keys %{ $store->{jobs} || {} }) {
        my $job = ProxmodCron::Config::effective($scope, $store, $id);
        next if !$job;

        my $row = {
            id => $id,
            scope => $scope,
            type => $job->{type},
            origin => $job->{origin},
            enabled => $job->{enabled},
            schedule => $job->{schedule},
            user => $job->{user},
            track => $job->{track},
            keep_output => $job->{keep_output},
        };

        $row->{owner} = $job->{owner} if defined $job->{owner};
        $row->{comment} = $job->{comment} if defined $job->{comment};
        $row->{nodes} = $job->{nodes} if defined $job->{nodes};

        $row->{renders} = ($scope eq 'node'
            || ProxmodCron::Config::targets_node($job, $nodename)) ? 1 : 0;

        my $argv = eval { ProxmodCron::Registry::build_command($job->{type}, $job) };
        if ($argv) {
            $row->{command} = join(' ', map { quote($_) } @$argv);
        } else {
            my $why = $@ || 'no command';
            chomp $why;
            $row->{unavailable} = $why;
        }

        my ($ok, $why) = ProxmodCron::Spec::validate($job->{schedule});
        if ($ok) {
            my $next = eval { ProxmodCron::Spec::next_run($job->{schedule}) };
            $row->{next_run} = $next if defined $next;
        } else {
            $row->{schedule_error} = $why;
        }

        push @rows, $row;
    }

    return \@rows;
}

1;
